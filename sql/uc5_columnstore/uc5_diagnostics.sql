USE [DBMS_EW_Group02];
SET NOCOUNT ON;
IF OBJECT_ID(N'dbo.UC5_Rowstore') IS NULL OR OBJECT_ID(N'dbo.UC5_Columnstore') IS NULL
 THROW 55100,'Run uc5_run.sql first.',1;
SET STATISTICS IO ON;SET STATISTICS TIME ON;SET STATISTICS XML ON;
SELECT OBJECT_TYPE,COUNT_BIG(*) n,SUM(COALESCE(OBJECT_ID,CONVERT(bigint,0))) s
FROM dbo.UC5_Rowstore GROUP BY OBJECT_TYPE;
SELECT OBJECT_TYPE,COUNT_BIG(*) n,SUM(COALESCE(OBJECT_ID,CONVERT(bigint,0))) s
FROM dbo.UC5_Columnstore GROUP BY OBJECT_TYPE;
SELECT ID,OWNER,OBJECT_NAME,OBJECT_TYPE FROM dbo.UC5_Rowstore WHERE ID=1;
SELECT ID,OWNER,OBJECT_NAME,OBJECT_TYPE FROM dbo.UC5_Columnstore WHERE ID=1;
SET STATISTICS XML OFF;SET STATISTICS IO OFF;SET STATISTICS TIME OFF;
